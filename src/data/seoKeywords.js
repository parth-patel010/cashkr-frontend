function uniqueJoin(list, limit = 40) {
  return [...new Set(list.filter(Boolean))].slice(0, limit).join(', ');
}

function buildCityKeywordPool(cityName) {
  const city = cityName;
  const pool = [];

  for (const t of CITY_INTENT_TEMPLATES) {
    pool.push(t.replace(/\{city\}/g, city));
  }
  for (const t of CITY_EXTRA_PHRASES) {
    pool.push(t.replace(/\{city\}/g, city));
  }

  for (const brand of CITY_BRANDS) {
    pool.push(`sell ${brand} in ${city}`);
    pool.push(`sell old ${brand} in ${city}`);
    pool.push(`sell used ${brand} in ${city}`);
    pool.push(`${brand} buyback ${city}`);
    pool.push(`${brand} sell for cash ${city}`);
  }

  for (const device of CITY_DEVICES) {
    for (const action of CITY_ACTIONS) {
      pool.push(`${action} ${device} in ${city}`);
      pool.push(`${action} ${device} ${city}`);
    }
    for (const mod of CITY_MODIFIERS) {
      pool.push(`sell ${device} ${mod} ${city}`);
      pool.push(`sell old ${device} ${mod} in ${city}`);
    }
  }

  for (const model of CITY_MODELS) {
    pool.push(`sell ${model} in ${city}`);
    pool.push(`sell old ${model} ${city}`);
    pool.push(`${model} buyback ${city}`);
    pool.push(`${model} resale price ${city}`);
  }

  pool.push(...CORE_BUYBACK_KEYWORDS);
  pool.push(...LONG_TAIL_KEYWORDS.slice(0, 40));

  return pool;
}

